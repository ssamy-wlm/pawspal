// Copies the shared design files into the mobile app so there is ONE source of truth:
//   design/tokens.json        -> apps/mobile/src/theme/tokens.json
//   assets/illustrations/*.svg -> apps/mobile/src/illustrations/index.ts (SVG strings for SvgXml)
//   assets/logo/*.svg          -> same file
//   docs/legal/*.md            -> apps/mobile/src/legal/index.ts (text + version, shown in the app)
// Run: node scripts/sync-shared.mjs   (also runs before every app start, see apps/mobile/package scripts)
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const app = join(root, 'apps/mobile/src');
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const banner = '// AUTO-GENERATED by scripts/sync-shared.mjs. Do not edit; edit the source file instead.\n';

mkdirSync(join(app, 'theme'), { recursive: true });
writeFileSync(join(app, 'theme/tokens.json'), readFileSync(join(root, 'design/tokens.json')));

const svgs = {};
for (const dir of ['assets/illustrations', 'assets/logo']) {
  for (const f of readdirSync(join(root, dir)).filter((f) => f.endsWith('.svg'))) {
    svgs[camel(basename(f, '.svg'))] = readFileSync(join(root, dir, f), 'utf8').trim();
  }
}
mkdirSync(join(app, 'illustrations'), { recursive: true });
writeFileSync(
  join(app, 'illustrations/index.ts'),
  banner + 'export const svg = ' + JSON.stringify(svgs, null, 2) + ' as const;\nexport type SvgName = keyof typeof svg;\n'
);

const docs = {};
for (const f of readdirSync(join(root, 'docs/legal')).filter((f) => f.endsWith('.md') && f !== 'README.md')) {
  const raw = readFileSync(join(root, 'docs/legal', f), 'utf8');
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const meta = Object.fromEntries((fm ? fm[1] : '').split('\n').map((l) => l.split(/:\s*/, 2)).filter((p) => p.length === 2));
  docs[camel(basename(f, '.md'))] = { title: meta.title, version: meta.version, effective: meta.effective, body: raw.replace(/^---\n[\s\S]*?\n---\n/, '').trim() };
}
mkdirSync(join(app, 'legal'), { recursive: true });
writeFileSync(
  join(app, 'legal/index.ts'),
  banner + 'export const legal = ' + JSON.stringify(docs, null, 2) + ' as const;\nexport type LegalDoc = keyof typeof legal;\n'
);
console.log(`synced tokens, ${Object.keys(svgs).length} svgs, ${Object.keys(docs).length} legal docs`);
